"""M3: train the target-only arm T0 and check its val gate (SPEC §15).

Per task:

1. Pick ``λ`` from the grid by val illicit-F1 of T0 at ``f = 0.25``, seed 0
   (§8.4); ties go to the smaller ``λ``. Written to ``runs/ft/<task>/lambda.json``
   and frozen for every arm of that task.
2. Train T0 at each configured fraction (the gate needs ``f = 1.0``) for every seed.
3. Refit the S0 random forest (notebook features, 50 trees, ``random_state = seed``)
   on the labelled *fitting split only* and score it on val. S0 itself trains on
   official-train, which includes val.
4. Gate, per seed and task: T0 val illicit-F1 at ``f = 1.0`` >= RF val
   illicit-F1 - margin. Both F1s use the val-optimal threshold (§6); the RF at
   0.5 is reported too.

Test is never scored. Writes ``reports/m3_t0_gate.md``; exits non-zero if the gate fails.

Usage: ``uv run python -m hns.eval.t0_gate [configs/t0.yaml]``
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

import numpy as np
import polars as pl
import torch
import yaml
from sklearn.ensemble import RandomForestClassifier

from hns.data.load import PARQUET_DIR, TX_FEATURES
from hns.data.split import SPLIT_DIR
from hns.eval.metrics import binary_metrics
from hns.eval.rf_anchor import git_sha
from hns.models.hrg import TaskData
from hns.transfer.finetune import RunConfig, train, val_metrics

RUNS = Path("runs/ft")
REPORT = Path("reports/m3_t0_gate.md")


def rf_fit_val(task: str, seed: int, n_estimators: int, parquet_dir: Path = PARQUET_DIR,
               split_dir: Path = SPLIT_DIR) -> dict:
    """S0's RF refit on the labelled fitting split, scored on val (raw features: min-max scaling
    does not change a tree's splits)."""
    sp = pl.read_parquet(split_dir / f"{task}_seed{seed}.parquet").filter(pl.col("split").is_in(["fit", "val"]))
    if task == "T":
        df = sp.join(pl.read_parquet(parquet_dir / "txs.parquet", columns=["tid", *TX_FEATURES]), on="tid")
        feats = TX_FEATURES
    else:
        w = pl.read_parquet(parquet_dir / "wallets.parquet")
        feats = [c for c in w.columns if c not in ("wid", "address", "class")]
        df = sp.join(w.select("wid", *feats), on="wid")
    fit, val = df.filter(pl.col("split") == "fit"), df.filter(pl.col("split") == "val")
    rf = RandomForestClassifier(n_estimators=n_estimators, random_state=seed, n_jobs=-1)
    rf.fit(fit.select(feats).to_numpy(), fit["y"].to_numpy())
    score = rf.predict_proba(val.select(feats).to_numpy())[:, 1]
    y = val["y"].to_numpy()
    return {"val_opt": val_metrics(y, score), "at_0.5": binary_metrics(y, score, 0.5), "n_fit": fit.height}


def select_lambda(task: str, cfg: dict, train_kw: dict, device, sha: str) -> float:
    path = RUNS / task / "lambda.json"
    lc = cfg["lambda"]
    if path.exists():
        rec = json.loads(path.read_text())
        if rec["grid"] == lc["grid"] and rec["fraction"] == lc["fraction"] and rec["seed"] == lc["seed"]:
            return rec["lambda"]
    data = TaskData(task, lc["seed"])
    f1 = {lam: train(RunConfig(task, lc["seed"], lc["fraction"], lam, **train_kw), data, RUNS, device, sha)["illicit_f1"]
          for lam in lc["grid"]}
    best = max(sorted(f1), key=lambda lam: f1[lam])  # sorted + strict max: ties go to the smaller λ
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps({**lc, "lambda": best, "val_illicit_f1": {str(k): v for k, v in f1.items()}}, indent=1))
    return best


def _ms(xs) -> str:
    return f"{np.mean(xs):.3f} ± {np.std(xs):.3f}"


def write_report(res: dict, cfg: dict, sha: str, path: Path = REPORT) -> None:
    margin = cfg["gate"]["margin"]
    lines = [
        "# M3: T0 target-only arm, val gate",
        "",
        "SPEC §15 M3. Gate, for every seed and task: T0 val illicit-F1 (f = 1.0) ≥ val illicit-F1 of the S0 RF "
        f"refit on the fitting split only, minus {margin}. Both at the val-optimal threshold (§6). Test is not scored.",
        "",
        f"Code: `{sha}`. Generated by `uv run python -m hns.eval.t0_gate`. Seeds {cfg['seeds']}, mean ± sd.",
        "",
        "## λ selection (T0, f = 0.25, seed 0, val illicit-F1)",
        "",
        "| Task | " + " | ".join(f"λ = {lam}" for lam in cfg["lambda"]["grid"]) + " | Chosen |",
        "|---|" + "---|" * (len(cfg["lambda"]["grid"]) + 1),
    ]
    for task, r in res.items():
        lam = json.loads((RUNS / task / "lambda.json").read_text())
        lines.append(f"| {task} | " + " | ".join(f"{lam['val_illicit_f1'][str(x)]:.3f}" for x in cfg["lambda"]["grid"])
                     + f" | {r['lambda']} |")
    lines += ["", "## Val metrics", "",
              "| Task | Model | f | Illicit F1 | P | R | PR-AUC | ROC-AUC | Best epoch |",
              "|---|---|---|---|---|---|---|---|---|"]
    for task, r in res.items():
        for f, runs in r["t0"].items():
            lines.append(f"| {task} | T0 (λ = {r['lambda']}) | {f} | {_ms([x['illicit_f1'] for x in runs])} "
                         f"| {_ms([x['illicit_precision'] for x in runs])} | {_ms([x['illicit_recall'] for x in runs])} "
                         f"| {_ms([x['pr_auc'] for x in runs])} | {_ms([x['roc_auc'] for x in runs])} "
                         f"| {', '.join(str(x['best_epoch']) for x in runs)} |")
        for key, name in (("val_opt", "RF, val-opt threshold"), ("at_0.5", "RF, threshold 0.5")):
            m = [x[key] for x in r["rf"]]
            lines.append(f"| {task} | {name} | 1.0 | {_ms([x['illicit_f1'] for x in m])} "
                         f"| {_ms([x['illicit_precision'] for x in m])} | {_ms([x['illicit_recall'] for x in m])} "
                         f"| {_ms([x['pr_auc'] for x in m])} | {_ms([x['roc_auc'] for x in m])} | — |")
    lines += ["", "## Gate", "", "| Task | Seed | T0 F1 | RF F1 | RF − margin | Pass |", "|---|---|---|---|---|---|"]
    for task, r in res.items():
        for s, (t0, rf, ok) in zip(cfg["seeds"], r["gate"]):
            lines.append(f"| {task} | {s} | {t0:.3f} | {rf:.3f} | {rf - margin:.3f} | {'yes' if ok else '**no**'} |")
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines) + "\n")


def main(cfg_path: str = "configs/t0.yaml") -> int:
    cfg = yaml.safe_load(Path(cfg_path).read_text())
    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    sha, kw = git_sha(), dict(cfg["train"], arm=cfg["arm"])
    if 1.0 not in cfg["fractions"]:
        raise ValueError("the gate needs fraction 1.0")
    res: dict = {}
    for task in cfg["tasks"]:
        lam = select_lambda(task, cfg, kw, device, sha)
        r = res[task] = {"lambda": lam, "t0": {f: [] for f in cfg["fractions"]}, "rf": [], "gate": []}
        for seed in cfg["seeds"]:
            data = TaskData(task, seed)
            for f in cfg["fractions"]:
                r["t0"][f].append(train(RunConfig(task, seed, f, lam, **kw), data, RUNS, device, sha))
            del data
            r["rf"].append(rf_fit_val(task, seed, cfg["gate"]["rf_n_estimators"]))
            t0_f1, rf_f1 = r["t0"][1.0][-1]["illicit_f1"], r["rf"][-1]["val_opt"]["illicit_f1"]
            ok = t0_f1 >= rf_f1 - cfg["gate"]["margin"]
            r["gate"].append((t0_f1, rf_f1, ok))
            print(f"M3 {task} seed {seed}: T0 val F1 {t0_f1:.3f} vs RF {rf_f1:.3f} -> {'PASS' if ok else 'FAIL'}")
    write_report(res, cfg, sha)
    failed = [(t, s) for t, r in res.items() for s, (_, _, ok) in zip(cfg["seeds"], r["gate"]) if not ok]
    if failed:
        print(f"M3 gate FAILED for {failed}", file=sys.stderr)
        return 1
    print(f"M3 gate passed; wrote {REPORT}")
    return 0


if __name__ == "__main__":
    sys.exit(main(*sys.argv[1:]))
