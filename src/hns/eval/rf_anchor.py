"""S0: the official Elliptic++ notebook random forest on the official splits (SPEC §6, M2).

A pipeline check, not a model comparison. Reproduces the guide repo's
classification notebooks:

- T: all 182 tx features, rows with nulls dropped, unknowns dropped, train
  ``Time step < 35``, test ``>= 35``.
- W: all 55 wallet features, de-duplicated, unknowns dropped,
  ``train_test_split(test_size=0.3, shuffle=False)`` in file order.
- ``RandomForestClassifier(n_estimators=50)``, labels illicit = 1, scored with
  ``predict`` (threshold 0.5).

The notebooks min-max-scale each feature on every row before dropping
unknowns, so the scaler sees test rows. The T notebook scales only
``columns[168:]`` of its frame (``txId, Time step, class, ...``), which is the
17 augmented features; the W notebook scales all 55. We report that
(``notebook``) and a train-only fit of the same columns (``train_only``). Accepts if illicit F1 is within the tolerance
of the published value for every seed and both scalings; exits non-zero
otherwise.

Usage: ``uv run python -m hns.eval.rf_anchor [configs/s0.yaml]``
"""

from __future__ import annotations

import json
import subprocess
import sys
from pathlib import Path

import numpy as np
import polars as pl
import yaml
from sklearn.ensemble import RandomForestClassifier

from hns.data.load import AUG_FEATURES, PARQUET_DIR, TX_FEATURES, wallet_feature_names
from hns.data.split import official_t, official_w
from hns.eval.metrics import binary_metrics

RUNS_DIR = Path("runs/s0")
REPORT = Path("reports/s0_anchor.md")


def git_sha() -> str:
    try:
        sha = subprocess.run(["git", "rev-parse", "HEAD"], capture_output=True, text=True, check=True).stdout.strip()
        dirty = subprocess.run(["git", "status", "--porcelain"], capture_output=True, text=True).stdout.strip()
        return sha + ("-dirty" if dirty else "")
    except (OSError, subprocess.CalledProcessError):
        return "unknown"


def task_data(task: str, parquet_dir: Path = PARQUET_DIR) -> dict:
    """Feature matrices for the official split, plus the notebook's scaler-fit rows."""
    if task == "T":
        txs = pl.read_parquet(parquet_dir / "txs.parquet")
        off = official_t(txs).join(txs.select("tid", *TX_FEATURES), on="tid")
        scaler_rows = txs.filter(pl.col("size").is_not_null()).select(TX_FEATURES).to_numpy()
        feats, ts = TX_FEATURES, off["ts"].to_numpy()
        scaled = [TX_FEATURES.index(f) for f in AUG_FEATURES]
    else:
        feats = wallet_feature_names()
        w = pl.read_parquet(parquet_dir / "wallets.parquet")
        off = official_w(w).join(w.select("wid", *feats), on="wid").sort("wid")
        scaler_rows = w.select(feats).to_numpy()
        ts, scaled = None, list(range(len(feats)))
    tr = (off["official"] == "train").to_numpy()
    X, y = off.select(feats).to_numpy().astype(np.float64), off["y"].to_numpy().astype(np.int64)
    return {"X_train": X[tr], "y_train": y[tr], "X_test": X[~tr], "y_test": y[~tr],
            "ts_test": None if ts is None else ts[~tr], "scaler_rows": scaler_rows.astype(np.float64),
            "features": feats, "scaled": scaled}


def minmax(fit_rows: np.ndarray, cols: list[int]):
    """Min-max scale columns ``cols`` with statistics from ``fit_rows``; other columns pass through."""
    lo, hi = fit_rows[:, cols].min(axis=0), fit_rows[:, cols].max(axis=0)
    span = np.where(hi > lo, hi - lo, 1.0)

    def scale(X: np.ndarray) -> np.ndarray:
        X = X.copy()
        X[:, cols] = (X[:, cols] - lo) / span
        return X
    return scale


def run_one(d: dict, scaling: str, seed: int, n_estimators: int) -> dict:
    scale = minmax(d["X_train"] if scaling == "train_only" else d["scaler_rows"], d["scaled"])
    rf = RandomForestClassifier(n_estimators=n_estimators, random_state=seed, n_jobs=-1)
    rf.fit(scale(d["X_train"]), d["y_train"])
    score = rf.predict_proba(scale(d["X_test"]))[:, 1]
    return binary_metrics(d["y_test"], score, threshold=0.5, ts=d["ts_test"])


def _ms(xs) -> str:
    return f"{np.mean(xs):.3f} ± {np.std(xs):.3f}"


def write_report(results: dict, cfg: dict, sha: str, path: Path = REPORT) -> None:
    lines = [
        "# S0: Elliptic++ notebook RF anchor",
        "",
        "Pipeline check (SPEC §6, M2). `RandomForestClassifier(n_estimators=50)` on the official splits, "
        f"seeds {cfg['seeds']}, mean ± sd over seeds. Illicit is the positive class; threshold 0.5 (`predict`).",
        "",
        f"Code: `{sha}`. Generated by `uv run python -m hns.eval.rf_anchor`.",
        "",
        "| Task | Scaling | Illicit P | Illicit R | Illicit F1 | Target F1 | PR-AUC | ROC-AUC | R@1% | R@5% | Micro-F1 | Macro-F1 | Pass |",
        "|---|---|---|---|---|---|---|---|---|---|---|---|---|",
    ]
    for task, by_scaling in results.items():
        acc = cfg["acceptance"][task]
        for scaling, runs in by_scaling.items():
            m = [r["metrics"] for r in runs]
            ok = all(r["pass"] for r in runs)
            lines.append(
                f"| {task} | {scaling} | {_ms([x['illicit_precision'] for x in m])} | {_ms([x['illicit_recall'] for x in m])} "
                f"| {_ms([x['illicit_f1'] for x in m])} | {acc['illicit_f1']} ± {acc['tol']} | {_ms([x['pr_auc'] for x in m])} "
                f"| {_ms([x['roc_auc'] for x in m])} | {_ms([x['recall_at_1pct'] for x in m])} | {_ms([x['recall_at_5pct'] for x in m])} "
                f"| {_ms([x['micro_f1'] for x in m])} | {_ms([x['macro_f1'] for x in m])} | {'yes' if ok else '**no**'} |")
    t = results.get("T", {}).get("train_only")
    if t:
        steps = sorted(t[0]["metrics"]["illicit_f1_per_ts"])
        lines += ["", "T illicit F1 per test time step (train-only scaling, mean over seeds). "
                  "The dark-market shutdown is at ts 43 (E18).", "",
                  "| ts | " + " | ".join(map(str, steps)) + " |", "|---|" + "---|" * len(steps),
                  "| F1 | " + " | ".join(f"{np.mean([r['metrics']['illicit_f1_per_ts'][s] for r in t]):.2f}"
                                       for s in steps) + " |"]
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines) + "\n")


def main(cfg_path: str = "configs/s0.yaml") -> int:
    cfg = yaml.safe_load(Path(cfg_path).read_text())
    sha = git_sha()
    results: dict = {}
    for task in ("T", "W"):
        d = task_data(task)
        acc = cfg["acceptance"][task]
        for scaling in cfg["scalings"]:
            for seed in cfg["seeds"]:
                m = run_one(d, scaling, seed, cfg["rf"]["n_estimators"])
                ok = abs(m["illicit_f1"] - acc["illicit_f1"]) <= acc["tol"]
                out = RUNS_DIR / task / f"rf_{scaling}" / str(seed)
                out.mkdir(parents=True, exist_ok=True)
                (out / "config.yaml").write_text(yaml.safe_dump(
                    {**cfg, "task": task, "scaling": scaling, "seed": seed, "git_sha": sha,
                     "n_train": int(len(d["y_train"])), "n_test": int(len(d["y_test"])),
                     "n_features": len(d["features"])}, sort_keys=False))
                (out / "metrics.jsonl").write_text(json.dumps({"split": "test", **m, "pass": ok}) + "\n")
                results.setdefault(task, {}).setdefault(scaling, []).append({"metrics": m, "pass": ok})
                print(f"S0 {task} {scaling} seed {seed}: illicit F1 {m['illicit_f1']:.3f} "
                      f"(P {m['illicit_precision']:.3f}, R {m['illicit_recall']:.3f}) "
                      f"target {acc['illicit_f1']}±{acc['tol']} -> {'PASS' if ok else 'FAIL'}")
    write_report(results, cfg, sha)
    failed = [(t, s) for t, bs in results.items() for s, rs in bs.items() if not all(r["pass"] for r in rs)]
    if failed:
        print(f"S0 FAILED for {failed}: stop and fix the pipeline (SPEC §6).", file=sys.stderr)
        return 1
    print(f"S0 passed; wrote {REPORT}")
    return 0


if __name__ == "__main__":
    sys.exit(main(*sys.argv[1:]))
